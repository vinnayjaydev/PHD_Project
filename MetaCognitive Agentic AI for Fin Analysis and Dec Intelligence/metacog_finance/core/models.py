"""Core domain models and schema definitions for the Meta-Cognitive Financial Framework.

All entities are strongly typed using Pydantic v2 to guarantee structured data contracts
between cognitive task agents, the hybrid RAG layer, the deterministic verification engine,
and the meta-cognitive supervisory controller.
"""

from __future__ import annotations

from enum import Enum
from typing import Any, Dict, List, Optional
from pydantic import BaseModel, Field


class DocumentSection(str, Enum):
    ITEM_1_BUSINESS = "Item 1. Business"
    ITEM_1A_RISK_FACTORS = "Item 1A. Risk Factors"
    ITEM_7_MDNA = "Item 7. Management's Discussion and Analysis (MD&A)"
    ITEM_8_FINANCIAL_STATEMENTS = "Item 8. Financial Statements and Supplementary Data"
    ITEM_9A_CONTROLS = "Item 9A. Controls and Procedures"
    FOOTNOTES = "Notes to Consolidated Financial Statements"
    EARNINGS_CALL = "Earnings Call Transcript"
    GENERAL = "General"


class DocumentChunk(BaseModel):
    """A granular chunk of financial text or tabular disclosure with temporal provenance."""
    chunk_id: str
    ticker: str
    doc_type: str = "10-K"  # 10-K, 10-Q, 8-K, Call
    fiscal_year: int
    fiscal_period: str = "FY"  # FY, Q1, Q2, Q3, Q4
    section: DocumentSection = DocumentSection.GENERAL
    content: str
    is_tabular: bool = False
    metadata: Dict[str, Any] = Field(default_factory=dict)
    relevance_score: Optional[float] = None


class FinancialStatement(BaseModel):
    """Point-in-time financial statement data extracted from SEC filings or XBRL."""
    ticker: str
    fiscal_year: int
    period: str = "FY"
    
    # Core Income Statement metrics (in millions USD unless specified)
    revenue: float = 0.0
    cost_of_goods_sold: float = 0.0
    gross_profit: float = 0.0
    research_and_development: float = 0.0
    sga_expenses: float = 0.0  # Selling, General & Administrative
    operating_income: float = 0.0  # EBIT
    interest_expense: float = 0.0
    tax_expense: float = 0.0
    net_income: float = 0.0
    
    # Core Balance Sheet metrics
    cash_and_equivalents: float = 0.0
    marketable_securities: float = 0.0
    accounts_receivable: float = 0.0
    inventories: float = 0.0
    total_current_assets: float = 0.0
    property_plant_equipment: float = 0.0
    goodwill_and_intangibles: float = 0.0
    total_assets: float = 0.0
    
    accounts_payable: float = 0.0
    short_term_debt: float = 0.0
    total_current_liabilities: float = 0.0
    long_term_debt: float = 0.0
    total_liabilities: float = 0.0
    retained_earnings: float = 0.0
    total_shareholders_equity: float = 0.0
    
    # Core Cash Flow metrics
    operating_cash_flow: float = 0.0
    capital_expenditures: float = 0.0  # Capex (usually positive or negative, standardized here as positive outflow)
    free_cash_flow: float = 0.0
    dividends_paid: float = 0.0
    share_repurchases: float = 0.0
    
    # Provenance tracking
    provenance_sources: Dict[str, str] = Field(default_factory=dict)


class FinancialRatios(BaseModel):
    """Standardized financial ratios with rigorous mathematical definitions."""
    # Liquidity
    current_ratio: float = 0.0
    quick_ratio: float = 0.0
    cash_ratio: float = 0.0
    
    # Solvency & Leverage
    debt_to_equity: float = 0.0
    debt_to_assets: float = 0.0
    interest_coverage_ratio: float = 0.0
    
    # Profitability & Returns
    gross_margin: float = 0.0
    operating_margin: float = 0.0
    net_profit_margin: float = 0.0
    return_on_assets_roa: float = 0.0
    return_on_equity_roe: float = 0.0
    return_on_invested_capital_roic: float = 0.0
    
    # Cash Flow & Earnings Quality
    fcf_conversion_ratio: float = 0.0  # FCF / Net Income (Values < 0.7 indicate accrual concerns)
    accrual_ratio: float = 0.0          # (Net Income - Operating Cash Flow) / Total Assets
    
    # Forensic Scores
    altman_z_score: float = 0.0
    altman_zone: str = "Unknown"        # "Safe (>2.99)", "Grey (1.81-2.99)", "Distress (<1.81)"
    
    beneish_m_score: float = -999.0
    manipulation_risk: str = "Low"      # "Low (<-1.78)", "High (>-1.78)"


class DiscrepancySeverity(str, Enum):
    LOW = "LOW"
    MEDIUM = "MEDIUM"
    HIGH = "HIGH"
    CRITICAL = "CRITICAL"


class EpistemicDiscrepancy(BaseModel):
    """An identified conflict between narrative management claims and verified quantitative facts."""
    discrepancy_id: str
    category: str  # e.g., "Narrative_vs_CashFlow", "Understated_Liability", "Margin_Contradiction"
    claim_in_narrative: str
    ground_truth_metric: str
    ground_truth_value: float
    reported_period: str
    severity: DiscrepancySeverity
    explanation: str
    source_citation: str


class MetaCognitiveAudit(BaseModel):
    """Audit snapshot generated by the Meta-Cognitive Supervisor at each decision cycle."""
    cycle_index: int
    verbalized_confidence: float = Field(..., ge=0.0, le=1.0, description="Raw confidence stated by cognitive agent")
    calibrated_confidence: float = Field(..., ge=0.0, le=1.0, description="Confidence mathematically penalized for discrepancies")
    grounding_faithfulness_score: float = Field(..., ge=0.0, le=1.0, description="Fraction of claims grounded in SEC citations")
    numerical_verification_pass: bool = Field(..., description="Whether all financial ratios reconcile deterministically")
    discrepancies: List[EpistemicDiscrepancy] = Field(default_factory=list)
    backtracking_triggered: bool = False
    backtracking_rationale: Optional[str] = None
    audit_verdict: str = "PASSED"  # PASSED, REVISED, REJECTED


class DecisionRecommendation(str, Enum):
    STRONG_BUY = "STRONG BUY"
    ACCUMULATE = "ACCUMULATE"
    HOLD_NEUTRAL = "HOLD / NEUTRAL"
    REDUCE_UNDERWEIGHT = "REDUCE / UNDERWEIGHT"
    CRITICAL_AVOID = "CRITICAL AVOID"


class DecisionIntelligenceMemo(BaseModel):
    """Final, calibrated decision output synthesized with explainable provenance and risk bounds."""
    ticker: str
    fiscal_year: int
    timestamp: str
    recommendation: DecisionRecommendation
    calibrated_confidence: float = Field(..., ge=0.0, le=1.0)
    confidence_tier: str  # "HIGH (>0.85)", "MODERATE (0.65-0.85)", "LOW (<0.65)"
    
    executive_thesis: str
    forensic_health_assessment: str
    quantitative_summary: Dict[str, Any]
    epistemic_discrepancies_detected: List[EpistemicDiscrepancy]
    scenario_analysis: Dict[str, str] = Field(
        default_factory=lambda: {
            "Bull_Case": "",
            "Base_Case": "",
            "Bear_Case": ""
        }
    )
    prescriptive_allocations: List[str] = Field(default_factory=list)
    meta_cognitive_trace: List[MetaCognitiveAudit] = Field(default_factory=list)
    citation_index: Dict[str, str] = Field(default_factory=dict)
